import { normalizeName } from '@stonekeep/core';
import type { MaskStrategy } from '@stonekeep/core/engine';
import type { SchemaMetadata } from './metadata.js';
import type { Proposal } from './proposal.js';
import type { ProposalProvider } from './providers.js';

const SUBJECT_NAMES =
  /^(users?|customers?|members?|accounts?|people|persons?|patients?|clients?|profiles?|contacts?)$/;
const RETAIN_NAMES = /(invoice|payment|transaction|ledger|receipt|credit_note|tax)/;
const BOOKKEEPING =
  /^(_?prisma_migrations|schema_migrations|knex_migrations|flyway_schema_history|migrations|typeorm_metadata)$/;

/** Column-level strategy from name, type and classification. Deterministic, offline. */
export function heuristicStrategy(
  column: string,
  type: string | null,
  rule: string | null,
): MaskStrategy {
  const n = normalizeName(column);
  const t = (type ?? '').toLowerCase();
  // Not classified as personal data: only free text gets masked.
  if (rule === null)
    return /(^|_)(notes?|comments?|body|message|description|bio)$/.test(n) ? 'token' : 'keep';
  if (/\b(inet|cidr)\b/.test(t)) return 'ip';
  if (/\b(date|timestamp|datetime)\b/.test(t)) return 'date';
  if (/\buuid\b/.test(t)) return 'uuid';
  if (/\bjsonb?\b/.test(t)) return 'json-empty';
  const numeric = /\b(int|integer|bigint|numeric|decimal|float|double|number)\b/.test(t);
  switch (rule) {
    case 'email':
      return 'email';
    case 'phone':
      return numeric ? 'number' : 'phone';
    case 'person-name':
      if (/(^|_)(first|given|fore)/.test(n)) return 'first-name';
      if (/(^|_)(last|family|sur|maiden)/.test(n)) return 'last-name';
      return 'full-name';
    case 'username':
      return 'username';
    case 'online-identifier':
      return /(^|_)ip(_|$)|addr/.test(n) ? 'ip' : 'token';
    case 'postal-address':
      if (/zip|post_?code|postal/.test(n)) return 'zip';
      if (/(^|_)(city|town)($|_)/.test(n)) return 'city';
      if (/lat|lon|lng|geo|coord|gps/.test(n)) return 'geo';
      return 'street';
    case 'date-of-birth':
      return 'date';
    default:
      return numeric ? 'number' : 'token';
  }
}

/** A rule-based proposal (no LLM): used offline, as the MCP planning tool, and as the eval baseline. */
export function heuristicProposal(metadata: SchemaMetadata): Proposal {
  const scored = metadata.entities.map((e) => ({
    e,
    pii: e.columns.filter((c) => c.pii).length,
    named: SUBJECT_NAMES.test(normalizeName(e.name)),
  }));
  const subject =
    scored.find((s) => s.named && s.pii > 0) ?? [...scored].sort((a, b) => b.pii - a.pii)[0];
  const subjectName = subject?.e.name ?? 'users';
  const key = subject?.e.columns.find((c) => c.name === 'id')?.name ?? 'id';
  const subjectRef = normalizeName(subjectName).replace(/s$/, '');

  const mask: Proposal['mask'] = [];
  const retain: Proposal['retain'] = [];
  const foreignKeys: Proposal['foreignKeys'] = [];
  const exclude: string[] = [];
  for (const e of metadata.entities) {
    const n = normalizeName(e.name);
    if (BOOKKEEPING.test(n)) {
      exclude.push(e.name);
      continue;
    }
    for (const c of e.columns) {
      const s = heuristicStrategy(c.name, c.type, c.pii?.rule ?? null);
      if (s !== 'keep') mask.push({ table: e.name, column: c.name, strategy: s });
      const cn = normalizeName(c.name);
      if (
        e.name !== subjectName &&
        /_(id|ref)$/.test(cn) &&
        (cn.startsWith(`${subjectRef}_`) ||
          /^(requester|owner|author|customer|account)_(id|ref)$/.test(cn))
      ) {
        foreignKeys.push({ table: e.name, column: c.name, references: `${subjectName}.${key}` });
      }
    }
    if (RETAIN_NAMES.test(n) && e.name !== subjectName) {
      retain.push({
        table: e.name,
        reason: 'Accounting records are usually subject to statutory retention (verify the period)',
        anonymize: e.columns
          .filter((c) => c.pii?.rule === 'email' || c.pii?.rule === 'phone')
          .map((c) => c.name),
      });
    }
  }
  return {
    subject: { table: subjectName, key },
    retain,
    foreignKeys,
    mask,
    exclude,
    notes: ['Generated by the offline heuristic planner: review every entry before use.'],
  };
}

export const heuristicProvider = (metadata: SchemaMetadata): ProposalProvider => ({
  name: 'heuristic',
  propose: () => Promise.resolve(heuristicProposal(metadata)),
});

const LABELS: Record<RopaLanguage, Labels> = { en: EN, pl: PL };

/** Escape text for a Markdown table cell. */
function cell(s: string): string {
  return s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function list(items: readonly string[], none: string): string {
  return items.length === 0 ? `_${none}_` : items.map(cell).join('<br>');
}

function categoryLabel(l: Labels, category: string): string {
  return l.categories[category] ?? category;
}

function activityTable(l: Labels, a: RopaActivity): string {
  const rows: [string, string][] = [
    [l.purposes, list(a.purposes, l.none)],
    [
      l.legalBasis,
      list(
        a.legalBasis.map((b) => l.bases[b]),
        l.none,
      ),
    ],
  ];
  if (a.specialCategories || a.specialCategoryConditions.length > 0) {
    rows.push([
      l.specialConditions,
      list(
        a.specialCategoryConditions.map((c) => l.conditions[c]),
        l.none,
      ),
    ]);
  }
  rows.push(
    [l.dataSubjects, list(a.dataSubjects, l.none)],
    [
      l.dataCategories,
      list(
        [...a.dataCategories.map((c) => categoryLabel(l, c.category)), ...a.extraDataCategories],
        l.none,
      ),
    ],
    [l.recipients, list(a.recipients, l.none)],
    [
      l.transfers,
      list(
        a.transfers.map((t) => `${t.country}: ${t.safeguard ?? `**${l.noSafeguard}**`}`),
        l.none,
      ),
    ],
    [l.retention, cell(a.retention)],
    [l.security, list(a.securityMeasures, l.none)],
  );
  return [
    `| ${l.element} | ${l.value} |`,
    '| --- | --- |',
    ...rows.map(([k, v]) => `| ${k} | ${v} |`),
  ].join('\n');
}

function issueLine(l: Labels, issue: RopaIssue): string {
  const where = issue.activity !== undefined ? `\`${issue.activity}\`: ` : '';
  return `- ${where}${l.issues[issue.code](cell(issue.subject ?? ''))}`;
}

/** Render the record as Markdown in the record's language. */
export function renderRopaMarkdown(ropa: Ropa): string {
  const l = LABELS[ropa.language];
  const out: string[] = [];
  const c = ropa.controller;
  out.push(
    `# ${l.title}`,
    '',
    `${l.subtitle} · ${l.asOf}: ${ropa.asOf}`,
    '',
    `> ${l.disclaimer}`,
    '',
  );

  out.push(`## ${l.controller}`, '');
  out.push(`- **${cell(c.name)}**`);
  if (c.address !== undefined) out.push(`- ${cell(c.address)}`);
  out.push(`- ${cell(c.contact)}`);
  if (c.representative) {
    out.push(
      `- ${l.representative}: ${cell(c.representative.name)}, ${cell(c.representative.contact)}`,
    );
  }
  for (const j of c.jointControllers) {
    out.push(`- ${l.jointControllers}: ${cell(j.name)}, ${cell(j.contact)}`);
  }
  if (ropa.dpo) out.push(`- ${l.dpo}: ${cell(ropa.dpo.name)}, ${cell(ropa.dpo.contact)}`);
  out.push('');

  ropa.activities.forEach((a, i) => {
    out.push(`## ${i + 1}. ${cell(a.name)}`, '', `\`${a.id}\``, '', activityTable(l, a), '');
  });

  if (ropa.issues.length > 0) {
    out.push(`## ${l.gaps}`, '', l.gapsIntro, '', ...ropa.issues.map((i) => issueLine(l, i)), '');
  }

  const withFields = ropa.activities.filter((a) => a.dataCategories.length > 0);
  if (withFields.length > 0) {
    out.push(`## ${l.appendix}`, '', l.appendixIntro, '');
    for (const a of withFields) {
      out.push(`### ${cell(a.name)}`, '', `| ${l.category} | ${l.fields} |`, '| --- | --- |');
      for (const dc of a.dataCategories) {
        out.push(
          `| ${categoryLabel(l, dc.category)} | ${dc.fields.map((f) => `\`${cell(f)}\``).join(', ')} |`,
        );
      }
      out.push('');
    }
  }
  return `${out.join('\n').trimEnd()}\n`;
}

/** Localised label for a GDPR Art. 6(1) legal basis, e.g. "art. 6 ust. 1 lit. b RODO (wykonanie umowy)". */
export function legalBasisLabel(language: RopaLanguage, basis: LegalBasis): string {
  return LABELS[language].bases[basis];
}

/** Localised label for an Art. 9(2) condition. */
export function specialConditionLabel(
  language: RopaLanguage,
  condition: SpecialCategoryCondition,
): string {
  return LABELS[language].conditions[condition];
}

/** Localised description of a datamap category, e.g. "Dane kontaktowe (e-mail, telefon)". */
export function dataCategoryLabel(language: RopaLanguage, category: string): string {
  return LABELS[language].categories[category] ?? category;
}
